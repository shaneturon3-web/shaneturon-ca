export const publisherShelfBuckets: PublisherShelfBucket[] = [];

export function getPublisherSurfaceItems(surface: PublisherSurfaceId) {
  return publisherCatalogue
    .filter((item) => item.surface.includes(surface))
    .sort((a, b) => (a.order ?? 999) - (b.order ?? 999));
}

export function getPublisherItemBySlug(slug: string) {
  return publisherCatalogue.find((item) => item.slug === slug);
}

export const publisherPublicItems = publisherCatalogue.filter(
  (item) => item.publicStatus === 'public' && item.routeEnabled,
);

export const publisherCandidateItems = publisherCatalogue.filter(
  (item) => item.audience === 'public-candidate' || item.publicSafe === 'partial',
);

export const publisherParkedItems = publisherCatalogue.filter(
  (item) => item.status === 'parked' || item.status === 'internal' || item.status === 'restricted',
);
